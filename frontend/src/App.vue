<template>
  <div class="form-container">
    <h2>Submit Your Brick!</h2>

    <form @submit.prevent="handleSubmit">

      <!-- File Input -->
      <div class="form-group">
        <label for="file-upload">Upload Brick:</label>
        <input id="file-upload" type="file" accept="image/png, image/jpeg, image/webp" @change="handleFileChange"
          required />
        <p v-if="fileError" class="error-text">{{ fileError }}</p>
        <p v-if="selectedFile" class="file-name">Selected: {{ selectedFile.name }}</p>
      </div>

      <!-- Preview Container -->
      <div class="preview-container">
        <canvas ref="previewCanvas" width="500" height="400" class="preview-image"></canvas>
        <!-- <img :src="previewUrl" alt="Image preview" class="preview-image" /> -->
      </div>

      <!-- Submit Button -->
      <button type="submit" :disabled="isSubmitting">
        {{ isSubmitting ? 'Uploading...' : 'Submit Form' }}
      </button>
    </form>

    <!-- Status Messages -->
    <div v-if="submitStatus" :class="['status-msg', submitStatus.type]">
      {{ submitStatus.message }}
    </div>
  </div>
</template>

<script setup>
import { ref, reactive, onMounted } from 'vue'

// Form text fields state
const formData = reactive({
  username: ''
})

// File state management
const selectedFile = ref(null);
const fileError = ref('');
const isSubmitting = ref(false);
const submitStatus = ref(null);
const previewCanvas = ref(null);
let boundingBox = [];
let img = null;


function drawImage() {
  const canvas = previewCanvas.value
  if (!canvas) return
  const ctx = canvas.getContext('2d')

  // Clear previous frame to avoid stacking drawings
  ctx.clearRect(0, 0, canvas.width, canvas.height)

  // Calculate the scale factor to fit within target bounds
  const scaleFactor = Math.min(500 / img.width, 400 / img.height);

  const newWidth = img.width * scaleFactor;
  const newHeight = img.height * scaleFactor;

  // center the image on the canvas
  const x = (canvas.width / 2) - (newWidth / 2);
  const y = (canvas.height / 2) - (newHeight / 2);

  ctx.drawImage(img, x, y, newWidth, newHeight);
  if (boundingBox != null) {
    ctx.strokeStyle = 'red';
    ctx.lineWidth = 5;
    ctx.strokeRect(
      (boundingBox[0])*scaleFactor + x, 
      (boundingBox[1])*scaleFactor + y, 
      (boundingBox[2]-boundingBox[0])*scaleFactor, 
      (boundingBox[3]-boundingBox[1])*scaleFactor);
  }
}


// Handle the file selection change event
const handleFileChange = (event) => {
  const file = event.target.files[0]
  fileError.value = ''

  if (!file) {
    selectedFile.value = null
    return
  }

  // Optional Validation: Restrict file size (e.g., max 5MB)
  const maxBytes = 5 * 1024 * 1024
  if (file.size > maxBytes) {
    fileError.value = 'File size exceeds the 5MB limit.'
    selectedFile.value = null
    event.target.value = '' // Clear input
    return
  }

  selectedFile.value = file

  const reader = new FileReader();
  reader.onload = function (e) {
    img = new Image();

    img.onload = function () {
      drawImage();
    };

    // Set the source of the image to the data URL generated by FileReader
    img.src = e.target.result;
  };
  boundingBox = [];

  // Convert the local file into a Base64 data URL
  reader.readAsDataURL(file);
}


// Handle form submission
const handleSubmit = async () => {
  if (!selectedFile.value) {
    fileError.value = 'Please select a file to upload.'
    return
  }

  isSubmitting.value = true
  submitStatus.value = null

  try {
    const payload = new FormData()

    // Put image file as payload
    payload.append('file', selectedFile.value)

    // TODO: FIX THIS PLEASE FOR THE LOVE OF GOD
    const response = await fetch('http://localhost:8000/uploadbrick', {
      method: 'POST',
      body: payload
      // No need to set the 'Content-Type' header manually. 
      // The browser automatically establishes 'multipart/form-data' along with the required boundary rules.
    })

    const json = await response.json();
    boundingBox = json['bounding_box']

    if (!response.ok) throw new Error('Server upload failed.')

    submitStatus.value = { type: 'success', message: 'Form submitted successfully!' }

    drawImage();
  } catch (error) {
    submitStatus.value = { type: 'error', message: error.message || 'An error occurred.' }
  } finally {
    isSubmitting.value = false
  }
}
</script>

